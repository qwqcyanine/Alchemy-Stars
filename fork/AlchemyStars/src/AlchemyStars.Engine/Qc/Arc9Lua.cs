    IReadOnlyDictionary<string, string>? GripPoses = null,
    IReadOnlyDictionary<string, (System.Numerics.Vector3 P, System.Numerics.Quaternion Q)>? MountPoses = null);

/// <summary>
/// Writes a standalone ARC9 SWEP (lua/weapons/arc9_&lt;name&gt;.lua, layout of ARC9-COD2019's arc9_cod2019_sm_mp5) and a
/// bodygroup attachment pack (lua/arc9/common/attachments_bulk/arc9_&lt;name&gt;_atts.lua, ARC9_Cod2019_Shared style).
/// Only arc9_base is required: the blend_move/blend_walk/empty/aim_blend handler from arc9_cod2019_base is inlined.
/// </summary>
public static partial class Arc9Lua
{
    private const float Fps = 30;

    // ARC9 animation key -> candidate compiled sequences (first present wins; bash takes all present).
    private static readonly (string Key, string[] Sources)[] Keys =
    [
        ("idle", ["idle"]), ("fire", ["fire"]), ("fire_empty", ["fire_last"]),
        ("reload", ["reload"]), ("reload_empty", ["reload_empty"]),
        ("reload_fast", ["reload_fast"]), ("reload_fast_empty", ["reload_empty_fast"]),
        ("ready", ["draw_first", "draw"]), ("draw", ["draw"]), ("holster", ["holster"]),
        ("idle_sprint", ["idle_sprint"]), ("enter_sprint", ["sprint_in"]), ("exit_sprint", ["sprint_out"]),
        ("super_sprint_in", ["super_sprint_in"]), ("super_sprint_out", ["super_sprint_out"]),
        ("inspect", ["inspect"]), ("firemode_1", ["semi_off"]), ("firemode_2", ["semi_on"]),
        ("bash", ["melee_hit_01", "melee_hit_02", "melee_hit_03"]),
    ];

    private static readonly Dictionary<string, string> SlotNames = new(StringComparer.OrdinalIgnoreCase)
    {
        ["tag_barrel_attach"] = "Barrel", ["tag_mag_attach"] = "Magazine", ["tag_stock_attach"] = "Stock",
        ["tag_pistolgrip_attach"] = "Rear Grip", ["tag_grip_attach"] = "Underbarrel", ["tag_scope"] = "Optic",
        ["tag_laser_attach"] = "Laser", ["tag_silencer"] = "Muzzle",
    };

    /// <summary>Returns the lua/ root that was written.</summary>
    public static string Write(string output, Arc9Weapon weapon)
    {
        var root = Path.Combine(output, "lua");
        var id = MwBaseLua.Identifier(weapon.Name);
        var className = "arc9_" + id;
        Directory.CreateDirectory(Path.Combine(root, "weapons"));
        Directory.CreateDirectory(Path.Combine(root, "arc9", "common", "attachments_bulk"));

        var elements = new StringBuilder("SWEP.AttachmentElements = {\n");
        var slots = new StringBuilder("SWEP.Attachments = {\n");
        var atts = new StringBuilder($"-- Generated by Alchemy Stars: bodygroup attachments for {className}.\nlocal ATT\n\n");
        var defaults = new StringBuilder();
        var packMounts = (weapon.PackParts ?? []).Select(part => part.Mount).Where(mount => weapon.Mounts?.Contains(mount) == true)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        var ownMounts = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        // ARC9 has no per-attachment animation table: magazine elements pick the _smag/_xmag clips via Hook_TranslateAnimation.
        var magElements = new List<(string Element, string Variant)>();
        // Barrels whose tip differs from the default barrel shift tag_silencer; bonemerged muzzle devices ignore AttPosMods.
        var muzzleMoves = new List<(string Element, System.Numerics.Vector3 Offset)>();
        var defaultMag = weapon.Groups.Select(group => QcAttachments.Capacity(group[0].Token)).FirstOrDefault(rounds => rounds is not null);
        for (var group = 0; group < weapon.Groups.Count; group++)
        {
            var parts = weapon.Groups[group];
            // Slots of optional extras (grip tapes) start on the blank bodygroup (index = part count) and every part is an attachment.
            var empty = weapon.EmptyDefaults is { } flags && group < flags.Count && flags[group];
            defaults.Append(empty ? parts.Length.ToString(CultureInfo.InvariantCulture) : "0");
            var category = $"{className}_{MwBaseLua.Identifier(parts.MinBy(part => part.Token.Length).Token.Split('_')[0])}";
            // CoD pack parts on this slot's own mount share the slot, so they and the gun's parts exclude each other.
            var packHere = packMounts.Contains(parts[0].Root) && ownMounts.Add(parts[0].Root);
            slots.AppendLine("    {")
                .AppendLine($"        PrintName = \"{SlotNames.GetValueOrDefault(parts[0].Root, parts[0].Token)}\",")
                .AppendLine(packHere ? $"        Category = {{\"{category}\", \"cod_{parts[0].Root}\"}}," : $"        Category = \"{category}\",")
                .AppendLine($"        Bone = \"{parts[0].Root}\",")
                .AppendLine("        Pos = Vector(0, 0, 0),")
                .AppendLine("    },");
            // Bodygroup value = part index; the first part is the default look, so only the others become attachments.
            for (var part = empty ? 0 : 1; part < parts.Length; part++)
            {
                var element = $"{className}_{MwBaseLua.Identifier(parts[part].Token)}";
                var capacity = QcAttachments.Capacity(parts[part].Token);
                if (QcAttachments.MagVariant(capacity, defaultMag) is { } variant) magElements.Add((element, variant));
                var bodygroups = $"Bodygroups = {{{{{group + 1}, {part}}}}}";
                if (weapon.MuzzleOffsets?.TryGetValue(parts[part].Token, out var offset) == true) muzzleMoves.Add((element, offset));
                elements.AppendLine($"    [\"{element}\"] = {{{bodygroups}}},");
                var token = parts[part].Token;
                var name = MwBaseLua.LuaString(weapon.CodPartNames?.GetValueOrDefault(token) ?? token);
                atts.AppendLine("ATT = {}\n")
                    .AppendLine($"ATT.PrintName = \"{name}\"")
                    .AppendLine($"ATT.CompactName = \"{name}\"")
                    .Append(weapon.PartIcons?.GetValueOrDefault(token) is { } icon ? $"ATT.Icon = Material(\"{icon}\")\n" : "")
                    .AppendLine("ATT.Description = [[]]")
                    .AppendLine("ATT.AutoStats = true")
                    .AppendLine("ATT.Free = true")
                    .AppendLine("ATT.MenuCategory = \"ARC9 - Generated\"")
                    .AppendLine($"ATT.Category = {{\"{category}\"}}")
                    .AppendLine($"ATT.ActivateElements = {{\"{element}\"}}");
                if (capacity is { } rounds) atts.AppendLine($"ATT.ClipSize = {rounds}"); // arc9_modern_warfare_classic mags use the bare stat
                if (weapon.Suppressed?.Contains(parts[part].Token) == true) atts.AppendLine("ATT.Silencer = true");
                var mods = weapon.CodPartMods?.GetValueOrDefault(token);
                atts.Append(StatLines(mods));
                // DamageLookupTable is a static stat RangeMult does not reach: the part brings the gun's steps rescaled.
                if (weapon.CodStats is { } cod && mods?.GetValueOrDefault("range_scale", 1) is { } range && Math.Abs(range - 1) > 0.001f)
                    atts.AppendLine($"ATT.DamageLookupTableOverride = {DamageLookup(cod, range)}");
                atts.AppendLine($"\nARC9.LoadAttachment(ATT, \"{element}\")\n");
            }
        }
        // Pack mounts with no slot of their own: one slot per category takes every mount's parts (Category list).
        // Pack parts bonemerge onto their own tag, so only the solve point moves: Hook_GetAttachmentPos shifts it from the
        // slot bone to the installed part's tag, which is where its Sights are measured from.
        var slotCount = weapon.Groups.Count;
        var suppressedElements = weapon.Groups.SelectMany(parts => parts.Skip(1)).Where(part => weapon.Suppressed?.Contains(part.Token) == true)
            .Select(part => $"\"{className}_{MwBaseLua.Identifier(part.Token)}\"").ToArray();
        var mountShifts = new List<(string Category, System.Numerics.Vector3 Offset)>();
        int? sightSlot = null;
        foreach (var pack in (weapon.PackParts ?? []).Where(part => packMounts.Contains(part.Mount) && !ownMounts.Contains(part.Mount)).GroupBy(part => part.Category))
        {
            var mounts = pack.Select(part => part.Mount).Distinct(StringComparer.OrdinalIgnoreCase).Order(StringComparer.Ordinal).ToArray();
            slotCount++;
            slots.AppendLine("    {")
                .AppendLine($"        PrintName = \"{PackSlotNames.GetValueOrDefault(pack.Key, pack.Key)}\",")
                .AppendLine(mounts.Length == 1 ? $"        Category = \"cod_{mounts[0]}\","
                    : "        Category = {\n" + string.Concat(mounts.Select(mount => $"            \"cod_{mount}\",\n")) + "        },")
                .AppendLine($"        Bone = \"{mounts[0]}\",")
                .AppendLine("        Pos = Vector(0, 0, 0),");
            // Integrally suppressed barrels take no muzzle device.
            if (pack.Key == "muzzles" && suppressedElements.Length > 0)
                slots.AppendLine("        ExcludeElements = {\n" + string.Concat(suppressedElements.Select(element => $"            {element},\n")) + "        },");
            slots.AppendLine("    },");
            if (pack.Key == "sights") sightSlot = slotCount;
            if (weapon.MountPoses is not { } poses || !poses.TryGetValue(mounts[0], out var home)) continue;
            foreach (var mount in mounts.Skip(1))
            {
                if (!poses.TryGetValue(mount, out var pose)) continue;
                var offset = System.Numerics.Vector3.Transform(pose.P - home.P, System.Numerics.Quaternion.Conjugate(home.Q));
                if (offset.Length() > 0.01f) mountShifts.Add(($"cod_{mount}", offset));
            }
        }
        elements.AppendLine("}");
        slots.AppendLine("}");

        var translate = new StringBuilder();
        // ARC9 keeps the base clip when the translated name has no animation (sh_animtranslate.lua HasAnimation check).
        if (magElements.Count > 0)
        {
            translate.AppendLine().AppendLine("SWEP.Hook_TranslateAnimation = function(self, anim)")
                .AppendLine("    local elements = self:GetElements()").AppendLine();
            foreach (var (element, variant) in magElements)
                translate.AppendLine($"    if elements[\"{element}\"] then return anim .. \"_{variant}\" end");
            translate.AppendLine().AppendLine("    return anim").AppendLine("end");
        }
        // Runs every DoBodygroups on the VM and WM; offsets are in tag_silencer's parent frame (ManipulateBonePosition space).
        if (muzzleMoves.Count > 0)
        {
            translate.AppendLine().AppendLine("-- Barrels with a longer or shorter tip move tag_silencer, which bonemerged muzzle devices follow.")
                .AppendLine("local muzzleMoves = {");
            foreach (var (element, offset) in muzzleMoves)
                translate.AppendLine($"    [\"{element}\"] = {LuaVector(offset)},");
            translate.AppendLine("}");
        }
        if (muzzleMoves.Count > 0 || sightSlot is not null)
        {
            translate.AppendLine().AppendLine("SWEP.Hook_ModifyBodygroups = function(self, data)").AppendLine("    local mdl = data.model");
            // Optics hide the receiver's iron sights ("tag_sight" bodygroup, WriteMeshes).
            if (sightSlot is { } slot)
                translate.AppendLine("    local sight = mdl:FindBodygroupByName(\"tag_sight\")").AppendLine()
                    .AppendLine("    if sight >= 0 then")
                    .AppendLine($"        mdl:SetBodygroup(sight, self.Attachments[{slot}].Installed and 1 or 0)")
                    .AppendLine("    end");
            if (muzzleMoves.Count > 0)
                translate.AppendLine().AppendLine("    local bone = mdl:LookupBone(\"tag_silencer\")").AppendLine("    if not bone then return end").AppendLine()
                    .AppendLine("    local pos = vector_origin").AppendLine()
                    .AppendLine("    for element, offset in pairs(muzzleMoves) do")
                    .AppendLine("        if data.elements[element] then").AppendLine("            pos = offset").AppendLine("        end").AppendLine("    end").AppendLine()
                    .AppendLine("    mdl:ManipulateBonePosition(bone, pos)");
            translate.AppendLine("end");
        }
        if (mountShifts.Count > 0)
        {
            // shortcut: offset only (the CoD sight tags share one parent, unrotated) and no WorldModelOffset.Scale; fine for
            // bonemerged parts, upgrade if a merged mount ever turns or a world model is scaled.
            translate.AppendLine().AppendLine("-- Merged slots: each pack part sits on its own tag, offset from the slot bone in that bone's frame.")
                .AppendLine("local mountOffsets = {");
            foreach (var (category, offset) in mountShifts)
                translate.AppendLine($"    [\"{category}\"] = {LuaVector(offset)},");
            translate.AppendLine("}").AppendLine()
                .AppendLine("SWEP.Hook_GetAttachmentPos = function(self, data)")
                .AppendLine("    local offset = data.atttbl and mountOffsets[data.atttbl.Category]")
                .AppendLine("    if not offset then return end").AppendLine()
                .AppendLine("    data.pos = LocalToWorld(offset, angle_zero, data.pos, data.ang)").AppendLine()
                .AppendLine("    return data").AppendLine("end");
        }
        File.WriteAllText(Path.Combine(root, "weapons", className + ".lua"),
            Header(weapon, className, defaultMag, defaults.ToString()) + "\n" + Animations(weapon.Sequences, weapon.Sounds ?? [], weapon.MagSwapFrames ?? new Dictionary<string, int>(),
                magElements.Select(item => item.Variant).Distinct().ToArray()) + translate + "\n" + elements + "\n" + slots);
        File.WriteAllText(Path.Combine(root, "arc9", "common", "attachments_bulk", className + "_atts.lua"), atts.ToString());
        return root;
    }

    private static string Animations(IReadOnlyDictionary<string, (int Frames, int? MagFrame, string Body)> sequences, IReadOnlyCollection<string> resolved, IReadOnlyDictionary<string, int> magSwaps,
        IReadOnlyList<string> magVariants)
    {
        var text = new StringBuilder("-------------------------- ANIMATIONS\n\nSWEP.Animations = {\n");
        // reload_smag/inspect_xmag copies of each reload/inspect key, played through Hook_TranslateAnimation.
        var keys = Keys.Concat(magVariants.SelectMany(variant => Keys
            .Where(entry => entry.Key.StartsWith("reload", StringComparison.Ordinal) || entry.Key == "inspect")
            .Select(entry => (Key: $"{entry.Key}_{variant}", Sources: entry.Sources.Select(source => $"{source}_{variant}").ToArray()))));
        foreach (var (key, sources) in keys)
        {
            var present = sources.Where(sequences.ContainsKey).ToArray();
            if (present.Length == 0) continue;
            if (key != "bash") present = present[..1];
            var (frames, mag, body) = sequences[present[0]];
            text.AppendLine($"    [\"{key}\"] = {{");
            text.AppendLine(present.Length == 1 ? $"        Source = \"{present[0]}\"," : $"        Source = {{{string.Join(", ", present.Select(item => $"\"{item}\""))}}},");
            if (key.StartsWith("reload", StringComparison.Ordinal))
            {
                var refill = mag is { } frame ? Math.Clamp(frame / (float)Math.Max(1, frames), 0.05f, 0.95f) : 0.75f;
                text.AppendLine($"        MinProgress = 0.9,\n        PeekProgress = 0.85,\n        RefillProgress = {Number(refill)},\n        FireASAP = true,");
                // BulletBones show the old round count until MagSwapTime, then the new magazine's.
                if (magSwaps.TryGetValue(present[0], out var swap)) text.AppendLine($"        MagSwapTime = {Number(swap / Fps)},");
            }
            else if (key is "ready" or "draw" or "inspect") text.AppendLine("        MinProgress = 0.8,\n        FireASAP = true,");
            var ik = IkTimeline(body, frames);
            if (ik.Count > 0)
                text.AppendLine("        IKTimeLine = {\n" + string.Concat(ik.Select(item => $"            {{t = {Number(item.T)}, lhik = {item.L}, rhik = {item.R}}},\n")) + "        },");
            // ARC9 suppresses QC sound events, so foley plays from here. Aliases registered by the generated
            // lua/arc9/shared/sh_arc9_<name>.lua are live; the rest stay commented until you map them.
            var sounds = SoundEvent().Matches(body).Select(match => (Frame: int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture), Name: match.Groups[2].Value)).ToArray();
            if (sounds.Length > 0)
                text.AppendLine("        EventTable = {\n" + string.Concat(sounds.Select(item => $"            {(resolved.Contains(item.Name) ? "" : "-- ")}{{s = \"{item.Name}\", t = {Number(item.Frame / Fps)}}},\n")) + "        },");
            text.AppendLine("    },");
        }
        return text.AppendLine("}").ToString();
    }

    /// <summary>MW Base IK events (9011 left / 9021 right, "1" on) as an ARC9 IKTimeLine; t is the fraction of the clip.</summary>
    private static List<(float T, int L, int R)> IkTimeline(string body, int frames)
    {
        var events = IkEvent().Matches(body).Select(match => (Frame: int.Parse(match.Groups[2].Value, CultureInfo.InvariantCulture),
            Left: match.Groups[1].Value == "9011", On: match.Groups[3].Value == "1")).OrderBy(item => item.Frame).ToArray();
        var timeline = new List<(float T, int L, int R)>();
        int left = 1, right = 1;
        foreach (var group in events.GroupBy(item => item.Frame))
        {
            var (oldLeft, oldRight) = (left, right);
            foreach (var item in group)
                if (item.Left) left = item.On ? 1 : 0; else right = item.On ? 1 : 0;
            if ((left, right) == (oldLeft, oldRight)) continue;
            // Hold the old state at the event and ease to the new one over ~8% of the clip (ARC9 lerps between keys).
            var t = Math.Clamp(group.Key / (float)Math.Max(1, frames), 0, 1);
            if (timeline.Count == 0 || timeline[^1].T < t) timeline.Add((t, oldLeft, oldRight));
            timeline.Add((Math.Min(1, Math.Max(t, timeline[^1].T) + 0.08f), left, right));
        }
        return timeline.Count == 0 || timeline.All(item => item is { L: 1, R: 1 }) ? [] : timeline;
    }

