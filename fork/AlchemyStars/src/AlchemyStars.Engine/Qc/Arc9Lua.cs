    private static string V(float? value) => ((value ?? 0) + 0f).ToString("0.###", CultureInfo.InvariantCulture);

    private static string Number(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);

    private static int Seed(string text) => (int)(text.Aggregate(17u, (hash, c) => hash * 31 + c) % 1000000);

    [GeneratedRegex("event (9011|9021) (\\d+) \"(\\d)\"")] private static partial Regex IkEvent();
