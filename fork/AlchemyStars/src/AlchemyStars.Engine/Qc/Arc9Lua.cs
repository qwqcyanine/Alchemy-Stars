    /// <summary>CoD's damage bands (Damage near->far, RangeM band ends, 0 = unused) as (end in m, damage); the last band never ends.</summary>
    private static List<(float? End, int Damage)> Bands(Cod20Stats.Weapon cod)
    {
        var bands = new List<(float? End, int Damage)>();
        for (var index = 0; index < cod.Damage.Length; index++)
        {
            if (cod.Damage[index] <= 0) continue;
            float? end = index < cod.RangeM.Length && cod.RangeM[index] > 0 ? cod.RangeM[index] : null;
            bands.Add((end, cod.Damage[index]));
            if (end is null) break;
        }
        if (bands.Count > 0 && bands[^1].End is not null) bands[^1] = (null, bands[^1].Damage);
        return bands;
    }

    /// <summary>ARC9 DamageLookupTable: the first entry whose range the hit is under gives its damage.</summary>
    internal static string DamageLookup(Cod20Stats.Weapon cod, float rangeScale = 1) =>
        "{\n" + string.Concat(Bands(cod).Select(band =>
            "    {" + (band.End.HasValue ? Number(band.End.Value * rangeScale) + " / ARC9.HUToM" : "math.huge") + $", {band.Damage}}},\n")) + "}";

    private static string DamageProfile(Cod20Stats.Weapon? cod)
    {
        if (cod is null || Bands(cod) is not { Count: > 0 } bands)
            return "SWEP.DamageMax = 25\nSWEP.DamageMin = 14\nSWEP.RangeMin = 10 / ARC9.HUToM\nSWEP.RangeMax = 30 / ARC9.HUToM";
        var ends = bands.Where(band => band.End is not null).Select(band => band.End!.Value).DefaultIfEmpty(0).ToArray();
        return $$"""
            -- CoD steps damage at each band end (no lerp); DamageMax/Min and the ranges are what the stats panel shows.
            SWEP.DamageMax = {{bands[0].Damage}}
            SWEP.DamageMin = {{bands[^1].Damage}}
            SWEP.RangeMin = {{Number(ends[0])}} / ARC9.HUToM
            SWEP.RangeMax = {{Number(ends[^1])}} / ARC9.HUToM
            SWEP.DamageLookupTable = {{DamageLookup(cod)}}
            SWEP.CurvedDamageScaling = false
            -- CoD's own location multipliers; arc9_mod_bodydamagecancel (on by default) strips GMod's.
            SWEP.BodyDamageMults = {
                [HITGROUP_HEAD] = {{Number(cod.Head)}},
                [HITGROUP_CHEST] = 1,
                [HITGROUP_STOMACH] = 1,
                [HITGROUP_LEFTARM] = 1,
                [HITGROUP_RIGHTARM] = 1,
                [HITGROUP_LEFTLEG] = {{Number(cod.Leg)}},
                [HITGROUP_RIGHTLEG] = {{Number(cod.Leg)}},
            }
            """;
    }

    /// <summary>CoD attachment scales (values != 1 only) as ARC9 ATT multipliers. ADS speed is a speed, ARC9's a time.</summary>
    internal static string StatLines(IReadOnlyDictionary<string, float>? scales)
    {
        if (scales is null) return "";
        var lines = new StringBuilder();
        void Line(string stat, float value) { if (Math.Abs(value - 1) > 0.001f) lines.AppendLine($"ATT.{stat} = {value.ToString("0.####", CultureInfo.InvariantCulture)}"); }
        foreach (var (key, value) in scales.OrderBy(item => item.Key, StringComparer.Ordinal))
            switch (key)
            {
                case "ads_speed_scale" when value > 0: Line("AimDownSightsTimeMult", 1 / value); break;
                case "sprint_to_fire_scale": Line("SprintToFireTimeMult", value); break;
                case "recoil_vertical_scale": Line("RecoilUpMult", value); break;
                case "recoil_horizontal_scale": Line("RecoilSideMult", value); break;
                case "gun_kick_scale": Line("RecoilKickMult", value); break;
                case "range_scale": Line("RangeMinMult", value); Line("RangeMaxMult", value); break;
                case "bullet_velocity_scale": Line("PhysBulletMuzzleVelocityMult", value); break;
                case "hip_spread_max_scale": Line("SpreadMultHipFire", value); break;
                case "move_speed_scale": Line("SpeedMult", value); break;
            }
        return lines.ToString();
    }

