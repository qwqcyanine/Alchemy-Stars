            local owner = self:GetOwner()
            if not owner:IsPlayer() then return end

            local clip, delta = self:Clip1(), self:GetSightAmount()
            ent:SetPoseParameter("aim_blend", Lerp(math.cos(delta * (math.pi / 2)), 1, 0))
            ent:SetPoseParameter("empty", clip == 0 and 1 or 0)
            if iswm then return end

            {{{(weapon.GripPoses is { Count: > 0 } ? GripPoseLines : "")}}}if self:GetCustomize() then
                ent:SetPoseParameter("aim_blend", 1)

                return
            end

            local maxspd, wspd = owner:GetWalkSpeed() or 250, owner:GetSlowWalkSpeed() or 100
            local vel = owner:OnGround() and owner:GetAbsVelocity():Length() * (1.1 - self.CustomizeDelta) or 0
            local spd = math.Clamp(math.Remap(vel, wspd, maxspd, 0, 1), 0, 1)
            local spd2 = math.Clamp(math.Remap(vel, 0, wspd, 0, 1), 0, 1) - spd
            local smoothing = 10 * math.Clamp(FrameTime(), 0, 0.3)
            self.MovePoseParam = Lerp(smoothing, self.MovePoseParam, math.Clamp(spd - delta, 0, 1))
            self.WalkPoseParam = Lerp(smoothing, self.WalkPoseParam, math.Clamp(spd2 - delta, 0, 1))
            ent:SetPoseParameter("blend_move", self.MovePoseParam)
            ent:SetPoseParameter("blend_walk", self.WalkPoseParam)
        end

        """.Replace("\r\n", "\n");

