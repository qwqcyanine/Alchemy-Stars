    CodFireSet? Fire = null,
    Cod20Stats.Weapon? CodStats = null,
    IReadOnlyDictionary<string, IReadOnlyDictionary<string, float>>? CodPartMods = null,
    IReadOnlyDictionary<string, string>? CodPartNames = null,
    IReadOnlyDictionary<string, string>? PartIcons = null,
    IReadOnlyList<(string Category, string Class, string Mount)>? PackParts = null,
    IReadOnlySet<string>? Mounts = null,
