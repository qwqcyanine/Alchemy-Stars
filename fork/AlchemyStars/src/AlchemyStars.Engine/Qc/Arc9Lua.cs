/// <param name="Groups">Attachment bodygroups in meshes.qc order (bodygroup index = position + 1): token + root bone per part.</param>
/// <param name="Sequences">Compiled sequence -> frame count at 30 fps, last reload checkpoint frame, QC body (for events).</param>
public sealed record Arc9Weapon(
    string Name,
    string ViewModel,
    string WorldModel,
    IReadOnlyList<(string Token, string Root)[]> Groups,
    IReadOnlyDictionary<string, (int Frames, int? MagFrame, string Body)> Sequences,
    (System.Numerics.Vector3 Pos, System.Numerics.Vector3 Ang)? Sight = null,
    string PrintName = "",
    IReadOnlyCollection<string>? Sounds = null,
    IReadOnlyList<string[]>? BulletBones = null,
    IReadOnlyDictionary<string, int>? MagSwapFrames = null,
    IReadOnlyList<bool>? EmptyDefaults = null,
